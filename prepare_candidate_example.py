"""Example: Prepare and verify a candidate free 1-generated iCRP.

This script demonstrates the workflow for verifying a candidate free algebra:
1. Compute the candidate (or load it from a file)
2. Add representative terms
3. Export to JSON format
4. Run verification

For a real candidate, you would typically:
- Load the output from free_rsi_icrp_product.py (UACalc format)
- Manually determine representative terms (by tracking construction in the product)
- Export as JSON with terms
- Run verify_free_icrp.py
"""

import json
from pathlib import Path

import numpy as np


def create_example_candidate():
    """Create a small example candidate free 2-generated iCRP.
    
    This is a toy example with 3 elements: {e, x, x*x}.
    In practice, the candidate would come from free_rsi_icrp_product.py
    or similar computation.
    """
    # Define the operations
    # Element 0 = e (identity)
    # Element 1 = x (generator)
    # Element 2 = x * x (fusion of generator with itself)
    
    # Fusion table: idempotent, commutative, e is identity
    fusion_table = [
        [0, 1, 2],  # e * e=e, e * x=x, e * (x*x)=x*x
        [1, 1, 2],  # x * e=x, x * x=x (idempotent), x * (x*x)=x*x
        [2, 2, 2],  # (x*x) * e=x*x, (x*x) * x=x*x, (x*x) * (x*x)=x*x
    ]
    
    # Arrow table: residual of fusion
    # a \ b is the largest c such that a * c <= b
    # For iCRP: (a * c <= b) <-> (c <= a \ b)
    arrow_table = [
        [0, 1, 2],  # e \ e=e, e \ x=x, e \ (x*x)=x*x
        [0, 0, 2],  # x \ e=e, x \ x=e (since x*x=x), x \ (x*x)=x*x
        [0, 0, 0],  # (x*x) \ e=e, (x*x) \ x=e, (x*x) \ (x*x)=e
    ]
    
    # Representative terms
    representative_terms = [
        "e",      # Element 0
        "x",      # Element 1
        "x * x",  # Element 2
    ]
    
    # Create the algebra data structure
    algebra_data = {
        "name": "Example Candidate F(1)",
        "cardinality": 3,
        "operations": {
            "*": {"arity": 2, "table": fusion_table},
            "\\": {"arity": 2, "table": arrow_table},
            "e": {"arity": 0, "table": 0},
        },
        "orderType": "icrp",
        "isFree": True,
        "generatorIndex": 1,  # Element 1 is the generator x
        "representativeTerms": representative_terms,
    }
    
    return algebra_data


def verify_candidate_example():
    """Run the complete verification workflow on the example."""
    import subprocess
    
    # Create the candidate
    print("Creating example candidate algebra...")
    candidate = create_example_candidate()
    
    # Save to JSON
    output_dir = Path("verification_example")
    output_dir.mkdir(exist_ok=True)
    
    candidate_path = output_dir / "candidate.json"
    with open(candidate_path, "w") as f:
        json.dump(candidate, f, indent=2)
    print(f"Saved candidate to {candidate_path}")
    
    # Run verification
    print("\nRunning verification (this may take a while)...")
    print("=" * 60)
    
    try:
        result = subprocess.run(
            [
                "python3",
                "verify_free_icrp.py",
                str(candidate_path),
                "-o",
                str(output_dir / "results"),
                "--proof-timeout",
                "10",
                "--counter-timeout",
                "10",
                "-v",
            ],
            capture_output=False,
            text=True,
        )
        
        print("=" * 60)
        if result.returncode == 0:
            print("✓ Verification completed successfully!")
        else:
            print("✗ Verification failed or incomplete")
        
        # Show summary
        summary_path = output_dir / "results" / "verification_summary.json"
        if summary_path.exists():
            with open(summary_path) as f:
                summary = json.load(f)
            
            print("\nSummary:")
            print(f"  Total equations: {summary['total_equations']}")
            print(f"  Proved:          {summary['proved']}")
            print(f"  Refuted:         {summary['refuted']}")
            print(f"  Unknown:         {summary['unknown']}")
            print(f"  Complete:        {summary['verification_complete']}")
        
    except FileNotFoundError:
        print("Error: verify_free_icrp.py not found or Python not available")
        print("Note: This requires pyp9m4 and provers to be installed")


