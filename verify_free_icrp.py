@dataclass
class EquationResult:
    """Result of attempting to verify one equation."""

    equation: str
    status: str  # "proved", "refuted", "unknown"
    prover: str | None = None  # Which prover succeeded (if proved)
    time_s: float = 0.0
    counterexample: str | None = None  # Mace4 model (if refuted)
    index: int | None = None  # position in the generated equation list
    description: str | None = None


@dataclass
class VerificationCheckpoint:
    """Checkpoint data for resumable verification."""

    results: list[EquationResult]
    proven_lemmas: list[str]
    next_index: int
    timestamp: float


def compute_representative_terms_bfs(
    operations: dict[str, Any],
    cardinality: int,
    generator_index: int = 1,
) -> list[str]:
    """Compute representative terms by BFS from the generator and constant e.
    
    Args:
        operations: dict mapping operation symbols to {arity, table}
        cardinality: number of elements
        generator_index: index of the generator element (default 1)
    
    Returns:
        List of representative terms, one per element
    """
    # Find the identity element
    e_index = operations.get("e", {}).get("table", 0) if "e" in operations else 0
    
    # Initialize terms
    terms: list[str | None] = [None] * cardinality
    terms[e_index] = "e"
    terms[generator_index] = "x"
    
    # BFS queue: (element_index, term_string)
    queue = deque([(e_index, "e"), (generator_index, "x")])
    
    # Get operation tables
    fusion_table = operations.get("*", {}).get("table", None)
    arrow_table = operations.get("\\", {}).get("table", None)
    
    while queue:
        elem_idx, elem_term = queue.popleft()
        
        # Try applying operations
        for other_idx in range(cardinality):
            if terms[other_idx] is None:
                continue
            
            other_term = terms[other_idx]
            
            # Try fusion: elem * other
            if fusion_table is not None:
                result = fusion_table[elem_idx][other_idx]
                if terms[result] is None:
                    new_term = f"({elem_term} * {other_term})"
                    terms[result] = new_term
                    queue.append((result, new_term))
            
            # Try fusion: other * elem
            if fusion_table is not None and other_idx != elem_idx:
                result = fusion_table[other_idx][elem_idx]
                if terms[result] is None:
                    new_term = f"({other_term} * {elem_term})"
                    terms[result] = new_term
                    queue.append((result, new_term))
            
            # Try arrow: elem \ other
            if arrow_table is not None:
                result = arrow_table[elem_idx][other_idx]
                if terms[result] is None:
                    new_term = f"({elem_term} \\ {other_term})"
                    terms[result] = new_term
                    queue.append((result, new_term))
            
            # Try arrow: other \ elem
            if arrow_table is not None and other_idx != elem_idx:
                result = arrow_table[other_idx][elem_idx]
                if terms[result] is None:
                    new_term = f"({other_term} \\ {elem_term})"
                    terms[result] = new_term
                    queue.append((result, new_term))
    
    # Fill any remaining with generic names
    for i in range(cardinality):
        if terms[i] is None:
            terms[i] = f"elem_{i}"
            logger.warning(f"Element {i} not reachable from generator; using elem_{i}")
    
    return [t for t in terms if t is not None]


def load_algebra_from_json(json_path: Path) -> tuple[dict[str, Any], list[str], int]:
    """Load algebra from JSON format (primary input from free_icrp.py).

    Returns:
        operations: dict mapping operation symbols to {arity, table}
        representative_terms: list of representative terms per element
        cardinality: number of elements
    """
    with open(json_path, encoding="utf-8") as f:
        data = json.load(f)

    operations = data["operations"]
    cardinality = data["cardinality"]
    
    # Check if this is marked as a partial/incomplete algebra
    is_free = data.get("isFree", True)
    if not is_free:
        raise ValueError(
            f"{json_path} is marked as a partial algebra (isFree=false). "
            "The verifier requires a complete free algebra with all operations known."
        )

    # Extract or compute representative terms
    if "representativeTerms" in data:
        representative_terms = data["representativeTerms"]
        if len(representative_terms) != cardinality:
            raise ValueError(
                f"Mismatch: {len(representative_terms)} representative terms "
                f"but cardinality {cardinality}"
            )
    else:
        # Compute via BFS
        generator_index = data.get("generatorIndex", 1)
        logger.info("Representative terms not in JSON; computing via BFS")
        representative_terms = compute_representative_terms_bfs(
            operations, cardinality, generator_index
        )

    return operations, representative_terms, cardinality


def load_algebra_from_model(
    model_path: Path, generator_index: int | None = None
) -> tuple[dict[str, Any], list[str], int]:
    """Load algebra from Mace4 .model format (secondary input).

    Attempts to read representative terms from comments. If not found,
    computes them via BFS from the generator and constant e.

    Args:
        model_path: Path to .model file
        generator_index: Index of generator element (default: read from data, or 1 if absent)

    Returns:
        operations: dict mapping operation symbols to {arity, table}
        representative_terms: list of representative terms per element
        cardinality: number of elements
    """
    from pyp9m4 import parse_models_from_file

    # Read the file
    content = model_path.read_text(encoding="utf-8")

    # Try to find representative terms and generator index in comments
    representative_terms: list[str] | None = None
    found_generator_index: int | None = None
    
    for line in content.splitlines():
        line = line.strip()
        if line.startswith("%") and "representative_terms" in line.lower():
            # Format: % representative_terms: ["e", "x", "x * x", ...]
            try:
                json_part = line.split(":", 1)[1].strip()
                representative_terms = json.loads(json_part)
            except (IndexError, json.JSONDecodeError):
                pass
        elif line.startswith("%") and "generator_index" in line.lower():
            # Format: % generator_index: 1
            try:
                json_part = line.split(":", 1)[1].strip()
                found_generator_index = int(json_part)
            except (IndexError, ValueError):
                pass

    # Parse the model
    models = list(parse_models_from_file(str(model_path)))
    if not models:
        raise ValueError(f"No models found in {model_path}")

    model = models[0]
    cardinality = model.domain_size

    # Extract operations
    operations: dict[str, Any] = {}

    if "*" in model.function_symbols:
        dot = model.as_function("*")
        table = np.array(
            [[dot(i, j) for j in range(cardinality)] for i in range(cardinality)]
        )
        operations["*"] = {"arity": 2, "table": table.tolist()}

    if "\\" in model.function_symbols:
        arrow = model.as_function("\\")
        table = np.array(
            [[arrow(i, j) for j in range(cardinality)] for i in range(cardinality)]
        )
        operations["\\"] = {"arity": 2, "table": table.tolist()}

    if "e" in model.function_symbols:
        e = model.as_function("e")()
        operations["e"] = {"arity": 0, "table": e}

    # Use generator index from file, command line, or default
    if generator_index is None:
        generator_index = found_generator_index if found_generator_index is not None else 1
        if found_generator_index is None:
            logger.warning(
                f"Generator index not found in {model_path}, using default value 1. "
                "Use --generator-index to specify if incorrect."
            )
    
    # Find e_index from the constant
    e_index = operations.get("e", {}).get("table", 0) if "e" in operations else 0
    
    # Compute representative terms if not in comments
    if representative_terms is None:
        logger.info(
            f"Representative terms not in {model_path}; computing via BFS "
            f"from generator {generator_index} and e at {e_index}"
        )
        representative_terms = compute_representative_terms_bfs(
            operations, cardinality, generator_index
        )

    if len(representative_terms) != cardinality:
        raise ValueError(
            f"Mismatch: {len(representative_terms)} representative terms "
            f"but cardinality {cardinality}"
        )

    return operations, representative_terms, cardinality


def load_algebra(
    path: Path, generator_index: int | None = None
) -> tuple[dict[str, Any], list[str], int]:
    """Load algebra from any supported format (.json or .model).

    Args:
        path: Path to algebra file
        generator_index: Index of generator element for .model files 
                        (default: read from file, or 1 if absent)

    Returns:
        operations: dict mapping operation symbols to {arity, table}
        representative_terms: list of representative terms per element
        cardinality: number of elements
    """
    suffix = path.suffix.lower()
    if suffix == ".json":
        return load_algebra_from_json(path)
    elif suffix == ".model":
        return load_algebra_from_model(path, generator_index)
    else:
        raise ValueError(
            f"Unsupported file format: {suffix}. Use .json (preferred) or .model"
        )


def generate_verification_equations(
    operations: dict[str, Any],
    representative_terms: list[str],
    cardinality: int,
) -> list[tuple[str, str]]:
    """Generate all operation table equations to verify.

    Returns:
        List of (equation_string, description) tuples.
        Example: ("(x * x) * x = x * x", "dot(1, 1) = 2")
    """
    equations = []

    for symbol, op_data in operations.items():
        arity = op_data["arity"]
        table = op_data["table"]

        if arity == 0:
            # Constant: e = rep(table)
            result_elem = table
            result_term = representative_terms[result_elem]
            equation = f"{symbol} = {result_term}"
            desc = f"constant {symbol} = {result_elem}"
            equations.append((equation, desc))

        elif arity == 2:
            # Binary operation: rep(i) op rep(j) = rep(table[i,j])
            table_array = np.array(table)
            for i in range(cardinality):
                for j in range(cardinality):
                    result_elem = int(table_array[i, j])
                    left_term = representative_terms[i]
                    right_term = representative_terms[j]
                    result_term = representative_terms[result_elem]

                    # Build the equation
                    if symbol == "\\":
                        # Arrow operation: Mace4 syntax uses backslash
                        left_expr = f"({left_term} \\ {right_term})"
                    elif symbol == "*":
                        left_expr = f"({left_term} * {right_term})"
                    else:
                        left_expr = f"{symbol}({left_term}, {right_term})"

                    equation = f"{left_expr} = {result_term}"
                    desc = f"{symbol}({i}, {j}) = {result_elem}"
                    equations.append((equation, desc))

        else:
            logger.warning(f"Skipping operation {symbol} with arity {arity}")

    return equations


async def try_prove_equation(
    equation: str,
    axioms: list[str],
    prover9: Prover9 | None,
    tptp_provers: list[TptpProverSpec],
    timeout_s: float,
) -> tuple[bool, str | None, float]:
    """Try to prove an equation using Prover9 and/or TPTP provers.

    Returns:
        (proved, prover_name, time_seconds)
    """
    start = time.time()

    # Build the theory
    goal = equation if equation.endswith(".") else f"{equation}."
    theory_text = to_p9m4("\n".join(axioms), goal)

    # Race solvers until one proves the goal (or all finish / time out).
    tasks: set[asyncio.Task] = set()

    if prover9 is not None:
        async def run_prover9():
            try:
                result = await asyncio.to_thread(
                    prover9.run, input=theory_text, timeout_s=timeout_s
                )
                # pyp9m4 uses ProverOutcome.proved, not a bare "success" string
                if result.outcome == ProverOutcome.proved:
                    return ("prover9", True)
                return ("prover9", False)
            except Exception as e:
                logger.debug(f"Prover9 error: {e}")
                return ("prover9", False)

        tasks.add(asyncio.create_task(run_prover9()))

    # TPTP provers
    if tptp_provers:
        try:
            tptp_text = convert_ladr_to_tptp(theory_text)

            for prover_spec in tptp_provers:
                async def run_tptp(spec=prover_spec):
                    try:
                        proved = await try_prove_tptp(
                            spec, tptp_text, timeout_s=timeout_s
                        )
                        return (spec.name, proved)
                    except Exception as e:
                        logger.debug(f"{spec.name} error: {e}")
                        return (spec.name, False)

                tasks.add(asyncio.create_task(run_tptp()))

        except Exception as e:
            logger.debug(f"TPTP conversion error: {e}")

    if not tasks:
        return (False, None, 0.0)

    deadline = start + timeout_s + 5
    while tasks:
        remaining_timeout = deadline - time.time()
        if remaining_timeout <= 0:
            break
        done, pending = await asyncio.wait(
            tasks, return_when=asyncio.FIRST_COMPLETED, timeout=remaining_timeout
        )
        if not done:
            break
        for task in done:
            try:
                prover_name, proved = task.result()
                if proved:
                    for t in pending:
                        t.cancel()
                    if pending:
                        await asyncio.gather(*pending, return_exceptions=True)
                    return (True, prover_name, time.time() - start)
            except Exception as e:
                logger.debug(f"Task error: {e}")
        tasks = pending

    for t in tasks:
        t.cancel()
    if tasks:
        await asyncio.gather(*tasks, return_exceptions=True)

    return (False, None, time.time() - start)


async def search_counterexample(
    equation: str,
    axioms: list[str],
    mace4: Mace4 | None,
    min_size: int,
    max_size: int,
    timeout_s: float,
) -> tuple[bool, str | None]:
    """Search for a counterexample using Mace4.

    Returns:
        (found, model_string)
    """
    if mace4 is None:
        return (False, None)

    # Mace4 searches models of assumptions; it does not treat goals as
    # constraints. Put the negated equation in the assumption list.
    body = equation[:-1] if equation.endswith(".") else equation
    theory_text = to_p9m4("\n".join(axioms) + f"\n-({body}).", "")

    try:
        # Search increasing domain sizes (Mace4 has no .run; use models()).
        for size in range(min_size, max_size + 1):
            size_timeout = timeout_s / (max_size - min_size + 1)
            mace4_options = Mace4CliOptions(
                max_seconds=max(1, int(size_timeout)),
                max_models=1,
                domain_size=size,
                end_size=size,
            )
            mace4_local = Mace4(options=mace4_options, timeout_s=size_timeout)

            models = await asyncio.to_thread(
                lambda m=mace4_local, t=theory_text: list(m.models(input=t))
            )
            if models:
                model = models[0]
                model_str = getattr(model, "raw", None) or str(model)
                return (True, model_str)

    except Exception as e:
        logger.debug(f"Mace4 error: {e}")

    return (False, None)


async def verify_equation(
    equation: str,
    description: str,
    axioms: list[str],
    prover9: Prover9 | None,
    mace4: Mace4 | None,
    tptp_provers: list[TptpProverSpec],
    proof_timeout_s: float,
    counterexample_min_size: int,
    counterexample_max_size: int,
    counterexample_timeout_s: float,
    counterexample_axioms: list[str] | None = None,
) -> EquationResult:
    """Verify a single equation: try to prove it, then search for counterexamples.

    *counterexample_axioms* (default: *axioms*) are given to Mace4. Lemmas are
    consequences of the base axioms, so the base axioms alone suffice there and
    keep Mace4 fast.
    """
    # Try to prove
    proved, prover_name, proof_time = await try_prove_equation(
        equation, axioms, prover9, tptp_provers, proof_timeout_s
    )

    if proved:
        return EquationResult(
            equation=equation,
            status="proved",
            prover=prover_name,
            time_s=proof_time,
        )

    # Search for counterexample
    found_counter, model_str = await search_counterexample(
        equation,
        counterexample_axioms if counterexample_axioms is not None else axioms,
        mace4,
        counterexample_min_size,
        counterexample_max_size,
        counterexample_timeout_s,
    )

    if found_counter:
        return EquationResult(
            equation=equation,
            status="refuted",
            time_s=proof_time,
            counterexample=model_str,
        )

    return EquationResult(
        equation=equation,
        status="unknown",
        time_s=proof_time,
    )


def save_checkpoint(
    checkpoint_path: Path,
    results: list[EquationResult],
    proven_lemmas: list[str],
    next_index: int,
):
    """Save verification progress to checkpoint file."""
    checkpoint = VerificationCheckpoint(
        results=results,
        proven_lemmas=proven_lemmas,
        next_index=next_index,
        timestamp=time.time(),
    )

    # Save as JSON
    checkpoint_data = {
        "results": [asdict(r) for r in results],
        "proven_lemmas": proven_lemmas,
        "next_index": next_index,
        "timestamp": checkpoint.timestamp,
    }

    with open(checkpoint_path, "w", encoding="utf-8") as f:
        json.dump(checkpoint_data, f, indent=2)


def load_checkpoint(checkpoint_path: Path) -> VerificationCheckpoint | None:
    """Load verification checkpoint if it exists."""
    if not checkpoint_path.exists():
        return None

    try:
        with open(checkpoint_path, encoding="utf-8") as f:
            data = json.load(f)

        known = set(EquationResult.__dataclass_fields__)
        results = [EquationResult(**{k: v for k, v in r.items() if k in known}) for r in data["results"]]
        return VerificationCheckpoint(
            results=results,
            proven_lemmas=data["proven_lemmas"],
            next_index=data["next_index"],
            timestamp=data["timestamp"],
        )
    except Exception as e:
        logger.warning(f"Failed to load checkpoint: {e}")
        return None


def _verify_equation_worker(
    equation: str,
    description: str,
    axioms: list[str],
    proof_timeout_s: float,
    counterexample_min_size: int,
    counterexample_max_size: int,
    counterexample_timeout_s: float,
    no_tptp: bool,
    counterexample_axioms: list[str] | None = None,
    use_prover9: bool = True,
    tptp_include: list[str] | None = None,
) -> EquationResult:
    """Worker function for parallel verification (runs in subprocess)."""
    # Setup provers in worker process
    prover9 = (
        Prover9(
            options=Prover9CliOptions(max_seconds=int(proof_timeout_s)),
            timeout_s=proof_timeout_s,
        )
        if use_prover9
        else None
    )

    mace4 = Mace4(
        options=Mace4CliOptions(
            max_seconds=int(counterexample_timeout_s),
            max_models=1,
        ),
        timeout_s=counterexample_timeout_s,
    )

    tptp_provers = [] if no_tptp else discover_tptp_provers(include=tptp_include)

    # Run verification synchronously in worker
    result = asyncio.run(
        verify_equation(
            equation,
            description,
            axioms,
            prover9,
            mace4,
            tptp_provers,
            proof_timeout_s,
            counterexample_min_size,
            counterexample_max_size,
            counterexample_timeout_s,
            counterexample_axioms,
        )
    )

    return result


def load_seed_lemmas(paths: Sequence[Path]) -> list[str]:
    """Read already-proven statements (one formula per line, ``%`` comments).

    Every line must parse as a fully parenthesised ``s = t.`` or ``s <= t.`` over
    ``x``, ``e``, ``*`` and ``\\`` (the format ``free_icrp.py`` writes);
    otherwise a ``ValueError`` names the offending line.
    """
    lemmas: list[str] = []
    seen: set[str] = set()
    for path in paths:
        for lineno, line in enumerate(Path(path).read_text(encoding="utf-8").splitlines(), 1):
            formula = line.strip()
            if not formula or formula.startswith("%"):
                continue
            if not formula.endswith("."):
                formula += "."
            try:
                parse_formula(formula)
            except TermParseError as exc:
                raise ValueError(f"{path}:{lineno}: cannot parse seed lemma {formula!r}: {exc}") from exc
            if formula not in seen:
                seen.add(formula)
                lemmas.append(formula)
    return lemmas


async def verify_algebra(
    algebra_path: Path,
    output_dir: Path,
    axiom_base: list[str],
    proof_timeout_s: float,
    counterexample_min_size: int,
    counterexample_max_size: int,
    counterexample_timeout_s: float,
    resume: bool,
    use_lemmas: bool,
    max_lemmas: int,
    no_tptp: bool,
    parallel: int,
    generator_index: int,
    seed_lemmas: list[str] | None = None,
    use_congruence: bool = True,
    use_prover9: bool = True,
    tptp_include: list[str] | None = None,
):
    """Main verification routine.

    Equations are dispatched to a pool of *parallel* worker processes, shortest
    first, with a rolling window: a new equation starts as soon as any worker is
    free, so one slow (timed-out) equation never stalls the others. Each prover
    call sees the base axioms, the *seed_lemmas* (statements proven earlier, e.g.
    by ``free_icrp.py``) and up to *max_lemmas* table equations proven so far.
    This is sound: every lemma was proven before the call that uses it started.

    With *use_congruence*, an equation that already follows from the seeds and
    proven equations by congruence closure (plus commutativity, idempotence and
    unit instances for ``*``) is marked proved by ``congruence`` without a prover.
    """
    seed_lemmas = list(seed_lemmas or [])
    # Load the algebra
    logger.info(f"Loading algebra from {algebra_path}")
    operations, representative_terms, cardinality = load_algebra(
        algebra_path, generator_index
    )
    logger.info(f"Loaded algebra with {cardinality} elements")
    logger.info(f"Operations: {list(operations.keys())}")

    # Generate equations to verify
    equations = generate_verification_equations(
        operations, representative_terms, cardinality
    )
    logger.info(f"Generated {len(equations)} equations to verify")

    # Setup checkpoint
    output_dir.mkdir(parents=True, exist_ok=True)
    checkpoint_path = output_dir / "verification_checkpoint.json"
    summary_path = output_dir / "verification_summary.json"
    counterexamples_dir = output_dir / "counterexamples"

    # Load checkpoint if resuming
    checkpoint = load_checkpoint(checkpoint_path) if resume else None
    results: list[EquationResult] = []
    proven_lemmas: list[str] = []
    if checkpoint:
        results = checkpoint.results
        proven_lemmas = checkpoint.proven_lemmas
        for k, r in enumerate(results):  # old checkpoints: results in order
            if r.index is None:
                r.index = k
        logger.info(f"Resuming from checkpoint: {len(results)}/{len(equations)} equations done")
    done = {r.index for r in results}

    congruence: CongruenceClosure | None = None
    if use_congruence:
        congruence = CongruenceClosure()
        for formula in seed_lemmas + proven_lemmas:
            congruence.add_formula(formula)
        merged = congruence.saturate_order()
        logger.info(
            f"Congruence closure: {congruence.equations_added} equations, "
            f"{congruence.inequalities_added} inequalities, {merged} order merges"
        )

    tptp_names = [] if no_tptp else [p.name for p in discover_tptp_provers(include=tptp_include)]
    logger.info(f"Provers: {(['prover9'] if use_prover9 else []) + tptp_names}")
    logger.info(f"Seed lemmas: {len(seed_lemmas)}; proof timeout {proof_timeout_s}s; parallel {parallel}")

    total = len(equations)
    order = sorted((k for k in range(total) if k not in done), key=lambda k: (len(equations[k][0]), k))
    counts = {"proved": 0, "refuted": 0, "unknown": 0}
    for r in results:
        counts[r.status] = counts.get(r.status, 0) + 1
    start_time = time.time()
    last_save = 0.0

    def first_undone() -> int:
        k = 0
        while k in done:
            k += 1
        return k

    def record(k: int, result: EquationResult) -> None:
        nonlocal last_save
        equation, description = equations[k]
        result.index = k
        result.description = description
        results.append(result)
        done.add(k)
        counts[result.status] = counts.get(result.status, 0) + 1
        if result.status == "proved":
            if result.prover != "congruence":
                logger.info(f"  [{k+1}] {description}: PROVED by {result.prover} in {result.time_s:.1f}s")
            lemma = equation if equation.endswith(".") else f"{equation}."
            if use_lemmas and result.prover != "congruence":
                proven_lemmas.append(lemma)
            if congruence is not None:
                congruence.add_formula(lemma)
        elif result.status == "refuted":
            logger.error(f"  [{k+1}] {description}: REFUTED (counterexample found): {equation}")
            if result.counterexample:
                counterexamples_dir.mkdir(parents=True, exist_ok=True)
                counter_path = counterexamples_dir / f"counter_{k:06d}.model"
                counter_path.write_text(result.counterexample, encoding="utf-8")
        else:
            logger.warning(f"  [{k+1}] {description}: UNKNOWN after {result.time_s:.0f}s: {equation}")
        now = time.time()
        if now - last_save > 30:
            save_checkpoint(checkpoint_path, results, proven_lemmas, first_undone())
            last_save = now
            elapsed = now - start_time
            n_done = len(done)
            logger.info(
                f"Progress: {n_done}/{total} done (proved {counts['proved']}, "
                f"unknown {counts['unknown']}, refuted {counts['refuted']}), "
                f"elapsed {elapsed/3600:.2f}h"
            )

    queue = deque(order)
    with ProcessPoolExecutor(max_workers=max(1, parallel)) as pool:
        running: dict[Any, int] = {}
        while queue or running:
            while queue and len(running) < max(1, parallel):
                k = queue.popleft()
                equation, description = equations[k]
                if congruence is not None and congruence.equation_holds(equation):
                    record(k, EquationResult(equation=equation, status="proved", prover="congruence"))
                    continue
                current_axioms = axiom_base + seed_lemmas
                if use_lemmas:
                    current_axioms = current_axioms + (
                        proven_lemmas[-max_lemmas:] if max_lemmas > 0 else proven_lemmas
                    )
                future = pool.submit(
                    _verify_equation_worker,
                    equation,
                    description,
                    current_axioms,
                    proof_timeout_s,
                    counterexample_min_size,
                    counterexample_max_size,
                    counterexample_timeout_s,
                    no_tptp,
                    axiom_base,
                    use_prover9,
                    tptp_include,
                )
                running[future] = k
            if not running:
                continue
            finished, _ = wait(list(running), return_when=FIRST_COMPLETED)
            for future in finished:
                k = running.pop(future)
                try:
                    result = future.result()
                except Exception as exc:  # worker crash: record as unknown
                    logger.error(f"  [{k+1}] worker error: {exc}")
                    result = EquationResult(equation=equations[k][0], status="unknown")
                record(k, result)

    # Unknowns may follow from equations proven later.
    if congruence is not None:
        upgraded = 0
        for r in results:
            if r.status == "unknown" and congruence.equation_holds(r.equation):
                r.status, r.prover = "proved", "congruence"
                upgraded += 1
        if upgraded:
            logger.info(f"Congruence closure upgraded {upgraded} unknown equations to proved")
    save_checkpoint(checkpoint_path, results, proven_lemmas, first_undone())

    # Generate summary
    proved_count = sum(1 for r in results if r.status == "proved")
    refuted_count = sum(1 for r in results if r.status == "refuted")
    unknown_count = sum(1 for r in results if r.status == "unknown")

    summary = {
        "algebra_path": str(algebra_path),
        "cardinality": cardinality,
        "total_equations": total,
        "proved": proved_count,
        "refuted": refuted_count,
        "unknown": unknown_count,
        "verification_complete": refuted_count == 0 and unknown_count == 0,
        "results": [asdict(r) for r in results],
    }

    with open(summary_path, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)

    logger.info(f"\n{'='*60}")
    logger.info("VERIFICATION SUMMARY")
    logger.info(f"{'='*60}")
    logger.info(f"Total equations: {total}")
    logger.info(f"Proved:          {proved_count}")
    logger.info(f"Refuted:         {refuted_count}")
    logger.info(f"Unknown:         {unknown_count}")
    logger.info(f"{'='*60}")

    if summary["verification_complete"]:
        logger.info("✓ VERIFICATION SUCCESSFUL: All equations proved!")
        logger.info("The candidate algebra is a valid free 1-generated iCRP.")
    else:
        if refuted_count > 0:
            logger.error(
                "✗ VERIFICATION FAILED: Some equations were refuted (counterexamples found)."
            )
            logger.error("The candidate algebra is NOT free. The RSI list may be incomplete.")
        if unknown_count > 0:
            logger.warning(
                "⚠ VERIFICATION INCOMPLETE: Some equations are neither proved nor refuted."
            )
            logger.warning("Consider increasing timeouts or using stronger provers.")

    logger.info(f"\nSummary saved to: {summary_path}")
    if checkpoint_path.exists():
        logger.info(f"Checkpoint saved to: {checkpoint_path}")

    return summary["verification_complete"]


def main():
    parser = argparse.ArgumentParser(
        description="Verify a candidate free 1-generated iCRP",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )

    parser.add_argument(
        "algebra",
        type=Path,
        help="Path to candidate algebra (.json preferred, or .model)",
    )

    parser.add_argument(
        "-o",
        "--output-dir",
        type=Path,
        default=Path("verification_output"),
        help="Output directory for results (default: verification_output)",
    )

    parser.add_argument(
        "--generator-index",
        type=int,
        default=None,
        help="Index of generator element for .model files (default: read from file, or 1 if absent)",
    )

    parser.add_argument(
        "--axiom-base",
        type=str,
        default="icrp",
        choices=["icrp", "idcrl", "rsi_icrp"],
        help="Base axiom system (default: icrp)",
    )

    parser.add_argument(
        "--proof-timeout",
        type=float,
        default=30.0,
        help="Timeout in seconds for each proof attempt (default: 30)",
    )

    parser.add_argument(
        "--counter-timeout",
        type=float,
        default=60.0,
        help="Timeout in seconds for counterexample search (default: 60)",
    )

    parser.add_argument(
        "--counter-min-size",
        type=int,
        default=2,
        help="Minimum domain size for Mace4 counterexample search (default: 2)",
    )

    parser.add_argument(
        "--counter-max-size",
        type=int,
        default=10,
        help="Maximum domain size for Mace4 counterexample search (default: 10)",
    )

    parser.add_argument(
        "--resume",
        action="store_true",
        help="Resume from checkpoint if it exists",
    )

    parser.add_argument(
        "--no-lemmas",
        action="store_true",
        help="Do not use previously proven equations as lemmas",
    )

    parser.add_argument(
        "--max-lemmas",
        type=int,
        default=100,
        help="Maximum number of recent lemmas to include (default: 100, 0=unlimited)",
    )

    parser.add_argument(
        "--no-tptp",
        action="store_true",
        help="Do not use TPTP provers (Vampire, Zipperposition)",
    )

    parser.add_argument(
        "--parallel",
        type=int,
        default=1,
        help="Number of equations to verify in parallel (default: 1 = sequential). "
        "Uses batch processing to maintain sound lemma sharing: lemmas proven in "
        "batch N become available in batch N+1.",
    )

    parser.add_argument(
        "--seed-lemmas",
        type=Path,
        action="append",
        default=[],
        help="File of already-proven statements (e.g. input/free_icrp_axioms.txt from a "
        "prover-based free_icrp.py run, NOT a --models run). Added to every prover call "
        "and to the congruence closure. Repeatable.",
    )

    parser.add_argument(
        "--no-congruence",
        action="store_true",
        help="Disable the congruence-closure fast path",
    )

    parser.add_argument(
        "--no-prover9",
        action="store_true",
        help="Do not run Prover9 (use only TPTP provers)",
    )

    parser.add_argument(
        "--tptp-provers",
        type=str,
        default="auto",
        help="Comma-separated TPTP provers (vampire,zipperposition) or 'auto' for all found",
    )

    parser.add_argument(
        "-v",
        "--verbose",
        action="store_true",
        help="Enable verbose logging",
    )

    args = parser.parse_args()

    # Setup logging
    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(message)s",
    )

    # Load axiom base
    if args.axiom_base == "icrp":
        from axioms import icrp_axioms as axiom_text
    elif args.axiom_base == "idcrl":
        from axioms import idcrl_axioms as axiom_text
    elif args.axiom_base == "rsi_icrp":
        from axioms import rsi_icrp_axioms as axiom_text

    axiom_base = [line.strip() for line in axiom_text.strip().split("\n") if line.strip()]
    seed_lemmas = load_seed_lemmas(args.seed_lemmas)
    if args.seed_lemmas:
        logging.getLogger(__name__).info(
            f"Loaded {len(seed_lemmas)} seed lemmas from {[str(p) for p in args.seed_lemmas]}"
        )
    tptp_include = (
        None
        if args.tptp_provers.strip().lower() == "auto"
        else [n.strip() for n in args.tptp_provers.split(",") if n.strip()]
    )

    # Run verification
    success = asyncio.run(
        verify_algebra(
            algebra_path=args.algebra,
            output_dir=args.output_dir,
            axiom_base=axiom_base,
            proof_timeout_s=args.proof_timeout,
            counterexample_min_size=args.counter_min_size,
            counterexample_max_size=args.counter_max_size,
            counterexample_timeout_s=args.counter_timeout,
            resume=args.resume,
            use_lemmas=not args.no_lemmas,
            max_lemmas=args.max_lemmas,
            no_tptp=args.no_tptp,
            parallel=args.parallel,
            generator_index=args.generator_index,
            seed_lemmas=seed_lemmas,
            use_congruence=not args.no_congruence,
            use_prover9=not args.no_prover9,
            tptp_include=tptp_include,
        )
    )

    sys.exit(0 if success else 1)


if __name__ == "__main__":
    main()
