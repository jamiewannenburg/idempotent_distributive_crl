"""Verify that a candidate free 1-generated iCRP is indeed free.

This script verifies a candidate free algebra (exported by free_icrp.py) by proving
that its operation tables are derivable from the iCRP axioms.

Verification approach:
1. Load the candidate algebra with representative terms for each element.
   Primary input: JSON from free_icrp.py (includes terms).
   Secondary: Mace4 .model file (computes terms via BFS if not in comments).
2. For each operation table entry (e.g., a*b=c), form the equation
   rep(a) * rep(b) = rep(c) and attempt to prove it from the iCRP axioms
   plus previously proven equations (used as lemmas).
3. If a proof succeeds within the time limit, record it and continue.
4. If no proof is found, search for a counterexample with Mace4. A counterexample
   means the axioms don't derive this equation (candidate is not free).
5. Equations that are neither proved nor refuted are marked as "unknown".

Note on distinctness: Distinct elements must be distinct in the free algebra.
We verify this implicitly: if the operation tables satisfy all iCRP equations
and the algebra is generated by a single element x, then it is a quotient of
the term algebra, hence free if the equations hold.

The verification is resumable (results checkpointed to a file), shows progress,
and supports parallelism across equations with sound lemma sharing.
"""

