"""Minimal UACalc library implementation for reading/writing .ua files.

This is a simplified implementation that provides the essential functionality
needed for the algebra export/import system.
"""

from __future__ import annotations

import re
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Any


class Operation:
    """An operation in a universal algebra."""
    
    def __init__(self, name: str, arity: int, table: list[Any]):
        self._name = name
        self._arity = arity
        self._table = table
        self._cardinality = None
        
        if arity == 0:
            # Constant: table is just the value
            if not isinstance(table, (list, tuple)):
                self._table = table
        elif arity == 1:
            # Unary: table is a list
            self._cardinality = len(table)
        elif arity == 2:
            # Binary: table is a 2D list
            self._cardinality = len(table)
        else:
            # Higher arity: table is flat
            if isinstance(table, list) and table:
                # Infer cardinality from table length
                n = int(len(table) ** (1.0 / arity) + 0.5)
                if n ** arity == len(table):
                    self._cardinality = n
    
    def symbol(self):
        """Return a SymbolWrapper with the operation name."""
        return SymbolWrapper(self._name)
    
    def arity(self) -> int:
        return self._arity
    
    def valueAt(self, args: list[int]) -> int:
        """Evaluate the operation at the given arguments."""
        if self._arity == 0:
            return self._table
        elif self._arity == 1:
            return self._table[args[0]]
        elif self._arity == 2:
            return self._table[args[0]][args[1]]
        else:
            # Flatten indices for higher arity
            idx = 0
            for arg in args:
                idx = idx * self._cardinality + arg
            return self._table[idx]


class SymbolWrapper:
    """Wrapper for operation symbols."""
    
    def __init__(self, name: str):
        self._name = name
    
    def name(self) -> str:
        return self._name


class Algebra:
    """A universal algebra."""
    
    def __init__(self, name: str, cardinality: int, operations: list[Operation]):
        self._name = name
        self._cardinality = cardinality
        self._operations = operations
        
        # Update operation cardinalities
        for op in self._operations:
            if op._cardinality is None and op._arity > 0:
                op._cardinality = cardinality
    
    def name(self) -> str:
        return self._name
    
    def cardinality(self) -> int:
        return self._cardinality
    
    def operations(self) -> list[Operation]:
        return self._operations
    
    def sub(self):
        """Return a SubalgebraWrapper for computing generated subalgebras."""
        return SubalgebraWrapper(self)


class SubalgebraWrapper:
    """Wrapper for subalgebra computations."""
    
    def __init__(self, algebra: Algebra):
        self.algebra = algebra
    
    def sg(self, generators: list[int]):
        """Compute the subalgebra generated by the given elements."""
        # Start with generators
        current = set(generators)
        frontier = list(current)
        
        # Expand by applying all operations
        while frontier:
            new_frontier = []
            for op in self.algebra.operations():
                if op.arity() == 0:
                    val = op.valueAt([])
                    if val not in current:
                        current.add(val)
                        new_frontier.append(val)
                elif op.arity() == 1:
                    for a in frontier:
                        val = op.valueAt([a])
                        if val not in current:
                            current.add(val)
                            new_frontier.append(val)
                elif op.arity() == 2:
                    # Apply to all combinations involving at least one frontier element
                    for a in current:
                        for b in frontier:
                            for args in [(a, b), (b, a)]:
                                val = op.valueAt(list(args))
                                if val not in current:
                                    current.add(val)
                                    new_frontier.append(val)
            frontier = new_frontier
        
        return SubalgebraResult(sorted(current))


class SubalgebraResult:
    """Result of a subalgebra computation."""
    
    def __init__(self, elements: list[int]):
        self.elements = elements
    
    def size(self) -> int:
        return len(self.elements)


class io:
    """I/O functions for UACalc files."""
    
    @staticmethod
    def parse_algebra_file(path: str) -> Algebra:
        """Parse a UACalc .ua file."""
        tree = ET.parse(path)
        root = tree.getroot()
        
        # Find basicAlgebra or freeAlgebra
        basic = root.find('.//basicAlgebra')
        if basic is None:
            basic = root.find('.//freeAlgebra')
        if basic is None:
            raise ValueError("No algebra found in file")
        
        name_elem = basic.find('algName')
        name = name_elem.text if name_elem is not None else "unnamed"
        
        card_elem = basic.find('cardinality')
        cardinality = int(card_elem.text) if card_elem is not None else 0
        
        # Parse operations
        operations = []
        ops_elem = basic.find('operations')
        if ops_elem is not None:
            for op_elem in ops_elem.findall('op'):
                symbol_elem = op_elem.find('.//opName')
                op_name = symbol_elem.text if symbol_elem is not None else "?"
                
                arity_elem = op_elem.find('.//arity')
                arity = int(arity_elem.text) if arity_elem is not None else 0
                
                # Parse operation table
                table_elem = op_elem.find('.//intArray')
                if table_elem is not None:
                    if arity == 0:
                        # Constant
                        row_elem = table_elem.find('row')
                        if row_elem is not None:
                            text = row_elem.text.strip()
                            # Handle both "[0]" and "0" formats
                            if text.startswith('[') and text.endswith(']'):
                                text = text[1:-1]
                            table = int(text)
                        else:
                            table = 0
                    elif arity == 1:
                        # Unary
                        table = []
                        for row_elem in table_elem.findall('row'):
                            table.append(int(row_elem.text))
                    elif arity == 2:
                        # Binary
                        table = []
                        for row_elem in table_elem.findall('row'):
                            row_text = row_elem.text
                            row = [int(x) for x in row_text.split(',')]
                            table.append(row)
                    else:
                        # Higher arity - flat
                        table = []
                        for row_elem in table_elem.findall('row'):
                            row_text = row_elem.text
                            if ',' in row_text:
                                table.extend(int(x) for x in row_text.split(','))
                            else:
                                table.append(int(row_text))
                    
                    operations.append(Operation(op_name, arity, table))
        
        return Algebra(name, cardinality, operations)
    
    @staticmethod
    def write_algebra_file(algebra: Algebra, path: str) -> None:
        """Write an Algebra to a UACalc .ua file."""
        # Ensure path ends with .ua
        path_obj = Path(path)
        if not path_obj.suffix:
            path_obj = path_obj.with_suffix('.ua')
        
        root = ET.Element('algebra')
        basic = ET.SubElement(root, 'basicAlgebra')
        
        name_elem = ET.SubElement(basic, 'algName')
        name_elem.text = algebra.name()
        
        card_elem = ET.SubElement(basic, 'cardinality')
        card_elem.text = str(algebra.cardinality())
        
        # Universe
        universe = ET.SubElement(basic, 'universe')
        for i in range(algebra.cardinality()):
            elem = ET.SubElement(universe, 'elem')
            elem.text = str(i)
        
        # Operations
        operations = ET.SubElement(basic, 'operations')
        
        for op in algebra.operations():
            op_elem = ET.SubElement(operations, 'op')
            
            symbol = ET.SubElement(op_elem, 'opSymbol')
            name_elem = ET.SubElement(symbol, 'opName')
            name_elem.text = op.symbol().name()
            
            arity_elem = ET.SubElement(symbol, 'arity')
            arity_elem.text = str(op.arity())
            
            table_elem = ET.SubElement(op_elem, 'opTable')
            int_array = ET.SubElement(table_elem, 'intArray')
            
            if op.arity() == 0:
                # Constant
                row = ET.SubElement(int_array, 'row')
                row.text = str(op.valueAt([]))
            elif op.arity() == 1:
                # Unary
                for i in range(algebra.cardinality()):
                    row = ET.SubElement(int_array, 'row')
                    row.set('r', f'[{i}]')
                    row.text = str(op.valueAt([i]))
            elif op.arity() == 2:
                # Binary
                for i in range(algebra.cardinality()):
                    row = ET.SubElement(int_array, 'row')
                    row.set('r', f'[{i}]')
                    row_values = [str(op.valueAt([i, j])) for j in range(algebra.cardinality())]
                    row.text = ','.join(row_values)
        
        # Write XML
        tree = ET.ElementTree(root)
        ET.indent(tree, space='  ')
        tree.write(str(path_obj), encoding='utf-8', xml_declaration=True)
    
    class Mace4Reader:
        """Read Mace4 model files and convert to Algebra objects."""
        
        @staticmethod
        def parse_algebra_list_from_file(path: str) -> list[Algebra]:
            """Parse all algebras from a Mace4 model file."""
            from pyp9m4 import parse_models_from_file
            
            models = list(parse_models_from_file(path))
            algebras = []
            
            for model in models:
                # Extract name
                name_match = re.search(r"number\s*=\s*(\d+)", model.raw)
                name = f"model{name_match.group(1)}" if name_match else "model"
                
                cardinality = model.domain_size
                operations = []
                
                # Extract operations from model
                # Common operations: *, \, e, ^, v
                for symbol in ['*', '\\', '^', 'v']:
                    if model.has_function(symbol):
                        func = model.as_function(symbol)
                        # Determine arity (assume binary for these)
                        try:
                            # Test if it's binary
                            func(0, 0)
                            arity = 2
                            table = [[func(i, j) for j in range(cardinality)]
                                     for i in range(cardinality)]
                        except TypeError:
                            # Might be unary
                            try:
                                func(0)
                                arity = 1
                                table = [func(i) for i in range(cardinality)]
                            except TypeError:
                                # Constant
                                arity = 0
                                table = func()
                        
                        operations.append(Operation(symbol, arity, table))
                
                # Check for constant 'e'
                if model.has_function('e'):
                    e_func = model.as_function('e')
                    try:
                        e_val = e_func()
                        operations.append(Operation('e', 0, e_val))
                    except TypeError:
                        pass
                
                algebras.append(Algebra(name, cardinality, operations))
            
            return algebras
